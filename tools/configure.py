#!/usr/bin/env python3
"""Configure the matching build. Runs inside the ror-build image:

    tools/dock python3 tools/configure.py            # everything
    tools/dock python3 tools/configure.py --no-split # only regenerate build.ninja

Steps:
  1. Extract the load image the build must reproduce (build/SLUS_214.48.rom,
     `objcopy -O binary` of the ELF) and check its SHA-1.
  2. Generate config/SLUS_214.48.yaml from the ELF's section table: .text,
     one subsegment per .gnu.linkonce section (inline methods and vtables,
     named after their mangled symbol), .vutext, data, rodata and bss.
  3. Run splat, which writes asm/ (git-ignored: it is game code), the
     linker script and include/.
  4. Write build.ninja: assemble, compile src/ with ee-gcc2.96 -Os, link,
     objcopy, and compare the result's SHA-1 against the original.
"""
import argparse
import hashlib
import re
import subprocess
import sys
from pathlib import Path

import ninja_syntax
from splat.util.ps2 import ps2elfinfo

ROOT = Path(__file__).resolve().parent.parent
ELF = ROOT / "disc/SLUS_214.48"
BASENAME = "SLUS_214.48"
ROM = ROOT / f"build/{BASENAME}.rom"
ROM_SHA1 = "fa157dc8763b2f376f6bb73a70b6a4c250181997"
CONFIG = ROOT / f"config/{BASENAME}.yaml"
SEG = "main"

COMPILER = "ee-gcc2.96"
CFLAGS = "-Os -G0 -fno-exceptions -x c++ -Iinclude -Isrc"  # no .eh_frame, no $gp access in the game
ASFLAGS = "-EL -march=r5900 -mabi=eabi -G0 -no-pad-sections -Iinclude"


def sh(cmd):
    subprocess.run(cmd, check=True)


def extract_rom():
    ROM.parent.mkdir(exist_ok=True)
    sh(["mips-linux-gnu-objcopy", "-O", "binary", "--gap-fill=0x00", str(ELF), str(ROM)])
    got = hashlib.sha1(ROM.read_bytes()).hexdigest()
    if got != ROM_SHA1:
        sys.exit(f"{ROM}: SHA-1 {got}, expected {ROM_SHA1}. Is disc/SLUS_214.48 the NTSC-U v1.00 ELF?")


def subsegment_name(section):
    """Stable, filesystem- and ninja-safe name for one ELF section."""
    n = section.name
    for prefix, folder in ((".gnu.linkonce.t.", "inline"), (".gnu.linkonce.d.", "vtbl")):
        if n.startswith(prefix):
            return f"{folder}/{re.sub(r'[^A-Za-z0-9_]', '_', n[len(prefix):])}"
    return f"{SEG}/{n.lstrip('.')}"


def write_config(info):
    lines = [
        "# Generated by tools/configure.py from the ELF's section table.",
        "# Do not edit by hand: change the generator instead.",
        "name: Rule of Rose (NTSC-U)",
        f"sha1: {ROM_SHA1}",
        "options:",
        f"  basename: {BASENAME}",
        f"  target_path: build/{BASENAME}.rom",
        f"  elf_path: build/{BASENAME}.elf",
        "  base_path: ..",
        "  platform: ps2",
        f"  compiler: {info.compiler}",
        f"  gp_value: 0x{info.gp:08X}",
        f"  ld_gp_expression: {SEG}_SBSS_START + 0x{info.gp - sbss_start(info):X}",
        "  asm_path: asm",
        "  src_path: src",
        "  build_path: build",
        f"  ld_script_path: build/{BASENAME}.ld",
        "  ld_dependencies: False",
        "  ld_wildcard_sections: True",
        "  ld_bss_contains_common: True",
        "  ld_align_section_vram_end: False  # else the image gains 4 bytes of tail padding",
        "  find_file_boundaries: False",
        "  o_as_suffix: True",
        "  symbol_addrs_path:",
        "    - symbols/symbol_addrs.txt",
        "    - config/symbol_addrs_manual.txt",
        "  undefined_funcs_auto_path: build/undefined_funcs_auto.txt",
        "  undefined_syms_auto_path: build/undefined_syms_auto.txt",
        "  string_encoding: ASCII",
        "  data_string_encoding: ASCII",
        "  rodata_string_guesser_level: 2",
        "  data_string_guesser_level: 2",
        "  named_regs_for_c_funcs: False",
        "  section_order:",
    ]
    lines += [f"    - {s}" for s, ok in info.elf_section_names if ok]
    lines.append("  auto_link_sections:")
    lines += [f"    - {s}" for s, ok in info.elf_section_names if ok and s not in (".text", ".vutext")]
    lines.append("segments:")
    for seg in info.segs:
        lines += [
            f"  - name: {SEG}",
            "    type: code",
            f"    start: 0x{seg.start:06X}",
            f"    vram: 0x{seg.vram:08X}",
            f"    bss_size: 0x{bss_size(seg, info):X}",
            "    subalign: 4  # original .gnu.linkonce.t sections are 4-aligned; gap bytes live in the asm",
            "    subsegments:",
        ]
        seen = set()
        splits = load_splits()
        columns = {".text": 0, ".rodata": 1, ".data": 2, ".bss": 3}
        for s in seg.sections:
            if s.name in columns and splits:
                col, typ = columns[s.name], s.splat_segment_type
                for row in splits:
                    if row[col] is None:
                        continue
                    if s.is_nobits:
                        lines.append(f"      - {{ type: {typ}, vram: 0x{row[col]:08X}, name: {row[4]} }} "
                                     f"# {s.name}")
                    else:
                        lines.append(f"      - [0x{row[col] - seg.vram:06X}, {typ}, {row[4]}] "
                                     f"# {s.name} ({row[5]})")
                continue
            name = subsegment_name(s)
            while name in seen:
                name += "_"
            seen.add(name)
            if s.is_nobits:
                lines.append(f"      - {{ type: {s.splat_segment_type}, vram: 0x{s.vram:08X}, "
                             f"name: {name} }} # {s.name}")
            else:
                lines.append(f"      - [0x{s.start:06X}, {s.splat_segment_type}, {name}] # {s.name}")
    lines.append(f"  - [0x{info.size:X}]")
    CONFIG.parent.mkdir(exist_ok=True)
    CONFIG.write_text("\n".join(lines) + "\n")


def bss_size(seg, info):
    """Bytes from the end of the loaded image to the end of .bss.

    splat's own value sums the NOBITS section sizes and so misses the
    alignment gaps before .sbss and between .sbss and .bss (0x48 bytes here),
    which would leave the rebuilt .bss short."""
    end = max(s.vram + s.size for s in seg.sections if s.is_nobits)
    return end - (seg.vram + info.size)


def load_splits():
    """config/splits.tsv (tools/split_files.py):
    [(text, rodata, data, bss, name, confidence)], None where a file has no chunk."""
    path = ROOT / "config/splits.tsv"
    if not path.exists():
        return []
    rows = []
    for line in path.read_text().splitlines():
        if line.startswith(("#", "text\t")) or not line.strip():
            continue
        *addrs, name, conf = line.split("\t")
        rows.append((*(None if a == "-" else int(a, 16) for a in addrs), name, conf))
    return rows


def sbss_start(info):
    return next(s.vram for seg in info.segs for s in seg.sections if s.name == ".sbss")


def write_ninja():
    # Only the asm the linker script uses: a re-split leaves stale files behind.
    ld = (ROOT / f"build/{BASENAME}.ld").read_text()
    linked = set(re.findall(r"build/(asm/\S+?)\.o\(", ld))
    asm = sorted(p for p in ROOT.glob("asm/**/*.s")
                 if str(p.relative_to(ROOT).with_suffix("")) in linked)
    src = sorted(ROOT.glob("src/**/*.cpp"))
    with open(ROOT / "build.ninja", "w") as f:
        n = ninja_syntax.Writer(f, width=120)
        n.comment("Generated by tools/configure.py. Run inside the ror-build image.")
        n.variable("asflags", ASFLAGS)
        n.variable("cflags", CFLAGS)
        n.rule("as", "mips-linux-gnu-as $asflags -o $out $in", description="AS $in")
        n.rule("cc", f"ee-cc {COMPILER} $cflags -c $in -o $out", description="CC $in")
        n.rule("ld", f"mips-linux-gnu-ld -EL -T build/{BASENAME}.ld "
                     "-T build/undefined_funcs_auto.txt -T build/undefined_syms_auto.txt "
                     "-T config/linker_extra.ld -Map build/$map -o $out",
               description="LD $out")
        n.rule("rom", "mips-linux-gnu-objcopy -O binary --gap-fill=0x00 $in $out",
               description="ROM $out")
        n.rule("check", f"echo '{ROM_SHA1}  $in' | sha1sum -c --quiet - && touch $out",
               description="CHECK $in")
        objs = []
        for p in asm:
            rel = p.relative_to(ROOT)
            o = f"build/{rel.with_suffix('.o')}"  # the splat linker script's naming
            n.build(o, "as", str(rel))
            objs.append(o)
        for p in src:
            rel = p.relative_to(ROOT)
            o = f"build/{rel.with_suffix('.o')}"
            n.build(o, "cc", str(rel))
            objs.append(o)
        elf = f"build/{BASENAME}.elf"
        n.build(elf, "ld", objs, variables={"map": f"{BASENAME}.map"},
                implicit=[f"build/{BASENAME}.ld", "config/linker_extra.ld"])
        n.build(f"build/{BASENAME}.built.rom", "rom", elf)
        n.build("build/ok", "check", f"build/{BASENAME}.built.rom")
        n.default("build/ok")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-split", action="store_true")
    a = ap.parse_args()
    if not a.no_split:
        extract_rom()
        info = ps2elfinfo.Ps2Elf.get_info(ELF, ELF.read_bytes())
        write_config(info)
        sh(["splat", "split", str(CONFIG)])
    write_ninja()
    print("Configured. Build and verify with: tools/dock ninja")


if __name__ == "__main__":
    main()
