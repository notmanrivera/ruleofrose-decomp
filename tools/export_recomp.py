#!/usr/bin/env python3
"""Export this project's function map for PS2Recomp (ran-j/PS2Recomp), the
PS2 static recompiler, so it can run on the game with our exact function
boundaries and names instead of a Ghidra export.

    tools/.venv/bin/python tools/export_recomp.py      # -> build/recomp/

Writes build/recomp/functions.csv in the format of PS2Recomp's
ExportPS2Functions.java ("Name,Start,End,Size", hex addresses, End
exclusive) and build/recomp/config.toml pointing at your own
disc/SLUS_214.48 and at that CSV. The functions come from the matching
build's ELF (build/SLUS_214.48.elf, from tools/dock ninja): every sized
function symbol, one per address, the original or mangled name when there
is one; since the build is byte-identical, the addresses are the game's.

The SDK functions (symbols/sce_symbols.tsv, matched by signature) are
listed in the TOML as comments: PS2Recomp replaces SDK calls with its
runtime's handlers (stubs = ["name@0xADDRESS"]) only for names its runtime
knows, so pick from them by hand.

PS2Recomp is GPL-3.0: running it on your own copy is fine, but linking a
port against its runtime makes the port GPL too (a decision for the
project, see notes/PROJECT_STATE.md).
"""
import csv
import sys
from pathlib import Path

from elftools.elf.elffile import ELFFile

ROOT = Path(__file__).resolve().parent.parent
ELF = ROOT / "build/SLUS_214.48.elf"
OUT = ROOT / "build/recomp"


def better(a, b):
    """The name to keep of two at one address: a real name over func_XXXX,
    a mangled one over a plain one, else the shorter."""
    def rank(n):
        return (n.startswith(("func_", "FUN_", "X")), "__" not in n, len(n))
    return a if rank(a) <= rank(b) else b


def functions():
    if not ELF.exists():
        sys.exit(f"{ELF.relative_to(ROOT)} not found: run the matching build (tools/dock ninja)")
    by_addr = {}
    with open(ELF, "rb") as f:
        for s in ELFFile(f).get_section_by_name(".symtab").iter_symbols():
            if s["st_info"]["type"] != "STT_FUNC" or s["st_size"] <= 0:
                continue
            a, n = s["st_value"], s.name
            if a in by_addr:
                by_addr[a] = (better(by_addr[a][0], n), max(by_addr[a][1], s["st_size"]))
            else:
                by_addr[a] = (n, s["st_size"])
    return sorted((a, n, size) for a, (n, size) in by_addr.items())


def sdk():
    path = ROOT / "symbols/sce_symbols.tsv"
    rows = []
    for ln in path.read_text().splitlines():
        w = ln.split("\t")
        if ln.startswith("#") or len(w) < 3 or w[0] == "addr":
            continue
        rows.append((int(w[0], 16), w[1], w[2]))
    return rows


def main():
    funcs = functions()
    OUT.mkdir(parents=True, exist_ok=True)
    with open(OUT / "functions.csv", "w", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["Name", "Start", "End", "Size"])
        for a, n, size in funcs:
            w.writerow([n, f"0x{a:08X}", f"0x{a + size:08X}", size])
    game_elf = ROOT / "disc/SLUS_214.48"
    lib = "\n".join(f'#   "{n}@0x{a:08X}",   # {library}' for a, library, n in sdk())
    (OUT / "config.toml").write_text(f"""# Generated by tools/export_recomp.py from the matching build's ELF
# (byte-identical to the game, so these are the game's addresses).
[general]
input = "{game_elf.as_posix()}"
output = "{(OUT / 'output').as_posix()}"
ghidra_output = "{(OUT / 'functions.csv').as_posix()}"
single_file_output = false
patch_syscalls = false
patch_cop0 = true
patch_cache = true
# SDK functions identified by signature; uncomment the ones PS2Recomp's
# runtime has handlers for (PS2_SYSCALL_LIST / PS2_STUB_LIST).
stubs = [
{lib}
]
skip = []
""", encoding="utf8", newline="\n")
    named = sum(1 for _, n, _ in funcs if not n.startswith(("func_", "FUN_")))
    print(f"build/recomp/functions.csv: {len(funcs)} functions ({named} with a real name), "
          f"build/recomp/config.toml (input: disc/SLUS_214.48, {len(sdk())} SDK functions listed)")


if __name__ == "__main__":
    main()
